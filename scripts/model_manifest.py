"""Catalogue the pretrained checkpoints, so the bytes can live outside git.

    uv run python scripts/model_manifest.py

Writes `docs/models.md` and `docs/models.sha256`.

Why this exists. The fourteen `best.pt` files are 48 MB each, 672 MB together,
and `.gitignore` excludes `*.pt` on purpose: git keeps every version of every
blob forever, so committing them would permanently inflate a repository that is
already 239 MB and would do it again on every re-run. The bytes therefore live
in a GitHub release, and what goes in git is this manifest — enough to say which
model is which, what produced it, and whether a downloaded copy is intact.

Verify a download against it with:

    sha256sum -c docs/models.sha256
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from natural_compounds.paths import ROOT, RUNS

CHUNK = 1 << 20


def digest(path: Path) -> str:
    """SHA256 of one file, read in chunks so a 48 MB model is not held twice."""
    checksum = hashlib.sha256()
    with path.open("rb") as handle:
        while block := handle.read(CHUNK):
            checksum.update(block)
    return checksum.hexdigest()


def rows() -> list[dict]:
    """One record per exported checkpoint, in curve order."""
    found = []
    for directory in sorted((RUNS / "pretrain").glob("pubchem_n*_s*")):
        model = directory / "best.pt"
        if not model.exists():
            continue
        size, seed = directory.name.replace("pubchem_n", "").split("_s")
        manifest = directory / "manifest.json"
        recorded = json.loads(manifest.read_text()) if manifest.exists() else {}
        fingerprint = directory / "inputs.sha256"
        found.append(
            {
                "run_id": directory.name,
                "size": int(size),
                "seed": int(seed),
                "bytes": model.stat().st_size,
                "sha256": digest(model),
                "inputs_sha256": fingerprint.read_text().strip() if fingerprint.exists() else None,
                "corpus": recorded.get("corpus", "pubchem"),
            }
        )
    return sorted(found, key=lambda r: (r["size"], r["seed"]))


def main() -> None:
    records = rows()
    if not records:
        raise SystemExit(f"no exported checkpoints under {RUNS / 'pretrain'}")

    checksums = ROOT / "docs" / "models.sha256"
    checksums.write_text("".join(f"{r['sha256']}  {r['run_id']}.pt\n" for r in records))

    total = sum(r["bytes"] for r in records) / 1e6
    lines = [
        "# Pretrained checkpoints",
        "",
        f"{len(records)} of 14 Stage C conditions, {total:.0f} MB in total.",
        "",
        "Generated by `scripts/model_manifest.py`. The bytes are not in git:",
        "`*.pt` is excluded on purpose, because git keeps every version of every",
        "blob forever and 672 MB of checkpoints would inflate the repository",
        "permanently and again on every re-run. They are published as release",
        "assets instead; this file records which model is which.",
        "",
        "Each file is one `BondMessagePassing` encoder of width 2048 and depth 6",
        "(8.71 M parameters) plus the 1,613-wide descriptor head it was trained",
        "with. Fine-tuning discards that head, so only the encoder is reused.",
        "",
        "Verify a download with `sha256sum -c docs/models.sha256`.",
        "",
        "| run id | corpus | size | seed | MB | sha256 (first 16) |",
        "|---|---|---|---|---|---|",
    ]
    for r in records:
        lines.append(
            f"| `{r['run_id']}` | {r['corpus']} | {r['size']:,} | {r['seed']} | "
            f"{r['bytes'] / 1e6:.0f} | `{r['sha256'][:16]}` |"
        )

    missing = 14 - len(records)
    if missing:
        lines += [
            "",
            f"**{missing} condition(s) not yet exported.** Re-run this script once",
            "they finish; it rewrites both files from whatever is on disk.",
        ]

    lines += [
        "",
        "## Publishing",
        "",
        "```bash",
        "# one asset per condition, named by run id",
        "for d in runs/pretrain/pubchem_n*_s*/; do",
        '    cp "$d/best.pt" "/tmp/$(basename "$d").pt"',
        "done",
        "gh release create stage-c-checkpoints /tmp/pubchem_n*_s*.pt \\",
        '    --title "Stage C pretrained checkpoints" \\',
        "    --notes-file docs/models.md",
        "```",
        "",
        "## Reproducing instead of downloading",
        "",
        "Every checkpoint is determined by the pinned code, the cached corpus and",
        "the two seeds, so it can be rebuilt rather than fetched:",
        "",
        "```bash",
        "sbatch slurm/stage-c-prep.sbatch                      # corpora and descriptors",
        "sbatch slurm/pretrain.sbatch pubchem 50000 0          # one condition",
        "```",
        "",
        "`inputs.sha256` in each run directory fingerprints the standardisation",
        "vectors and SMILES that condition trained against, which is what stops a",
        "resumed run continuing onto changed targets.",
        "",
    ]
    (ROOT / "docs" / "models.md").write_text("\n".join(lines))

    print(f"{len(records)} checkpoint(s), {total:.0f} MB")
    print("wrote docs/models.md and docs/models.sha256")


if __name__ == "__main__":
    main()
